#!/usr/bin/env python3
"""token_emit.py — DTCG design-token compiler for the glasspring skill.

Reads a W3C Design Tokens-flavored JSON (groups, `$value`/`value`, `{alias}`
references) and emits:
  tokens.css    — CSS custom properties (--kebab-case)
  tokens.swift  — Swift constants (struct GlasspringTokens)
  tokens.kt     — Kotlin object (GlasspringTokens)

DTCG notes: `$value` and `value` are both accepted; `{a.b}` aliases resolve to
another token's value; `$type`/`$description` are tolerated and ignored.

  Usage:
  python token_emit.py --selftest
  python token_emit.py --demo --out-dir <dir>     # write the demo token set out
  python token_emit.py tokens.json --out-dir out --wxss   # + WeChat tokens.wxss (px→rpx)
"""
from __future__ import annotations
import argparse, json, re, sys

def _kebab(name: str) -> str:
    s = re.sub(r"(?<!^)(?=[A-Z])", "-", name)  # split camelCase: accentRef -> accent-Ref
    return s.replace("_", "-").lower()

def _camel(name: str) -> str:
    parts = re.split(r"[-_.\s]+", name)
    return parts[0].lower() + "".join(p.capitalize() for p in parts[1:])

def _flatten(node: dict, prefix: str = "", descs: dict | None = None) -> dict:
    """Flatten nested token groups into {dotted.name: value}.

    $description metadata is collected into `descs` (dotted.name -> text) so
    measured-contrast / APCA annotations can travel with the token into the
    emitted CSS as comments (shadcn-bridge provenance, 2026-10-18)."""
    flat = {}
    for key, val in node.items():
        if key.startswith("$"):  # $value/$type/$description metadata at group level
            continue
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(val, dict):
            if descs is not None and isinstance(val.get("$description"), str):
                descs[path] = val["$description"]
            inner = val.get("$value", val.get("value"))
            if inner is not None and not isinstance(inner, dict):
                flat[path] = inner
            elif isinstance(inner, dict):
                flat.update(_flatten(inner, path, descs))
            else:
                flat.update(_flatten(val, path, descs))
        else:
            flat[path] = val
    return flat

def resolve_aliases(flat: dict, max_depth: int = 8) -> dict:
    """Resolve {other.token} alias references (DTCG alias syntax)."""
    resolved = dict(flat)
    pattern = re.compile(r"^\{([^{}]+)\}$")
    for _ in range(max_depth):
        changed = False
        for k, v in resolved.items():
            if isinstance(v, str):
                m = pattern.match(v.strip())
                if m and m.group(1) in resolved and m.group(1) != k:
                    target = resolved[m.group(1)]
                    if not pattern.match(str(target).strip()):
                        resolved[k] = target
                        changed = True
        if not changed:
            break
    return resolved

def _swift_type(value) -> str:
    if isinstance(value, bool): return "Bool"
    if isinstance(value, int): return "Int"
    if isinstance(value, float): return "Double"
    return "String"

def _swift_str(value) -> str:
    if isinstance(value, bool): return "true" if value else "false"
    if isinstance(value, str): return json.dumps(value)
    return str(value)

def emit_css(flat: dict, descs: dict | None = None) -> str:
    lines = [":root {"]
    for k in sorted(flat):
        var = f"--{_kebab(k.replace('.', '-'))}"
        note = descs.get(k) if descs else None
        lines.append(f"  {var}: {flat[k]};" + (f"  /* {note} */" if note else ""))
    lines.append("}")
    return "\n".join(lines)

def emit_swift(flat: dict) -> str:
    lines = ["// Generated by token_emit.py — do not edit by hand.",
             "enum GlasspringTokens {"]
    for k in sorted(flat):
        prop = _camel(k.replace(".", "-"))
        val = _swift_str(flat[k]) if not isinstance(flat[k], (int, float)) else str(flat[k])
        lines.append(f"    static let {prop}: {_swift_type(flat[k])} = {val}")
    lines.append("}")
    return "\n".join(lines)

def emit_kotlin(flat: dict) -> str:
    lines = ["// Generated by token_emit.py — do not edit by hand.",
             "object GlasspringTokens {"]
    for k in sorted(flat):
        prop = _camel(k.replace(".", "-"))
        val = json.dumps(flat[k]) if isinstance(flat[k], str) else str(flat[k])
        lines.append(f"    val {prop}: String = {val}")
    lines.append("}")
    return "\n".join(lines)

def emit_wxss(flat: dict, descs: dict | None = None, design_width: int = 375) -> str:
    """WeChat WXSS target: tokens in `page {}`
    with px lengths converted to rpx (750rpx = design_width px → 1px = 750/design_width rpx).
    Only px lengths convert; ms/oklch/%/unitless values pass through untouched.
    Closes the three-file hand-sync drift risk (tokens.css / tokens-v3.wxss / mirror)."""
    scale = 750.0 / design_width

    def to_rpx(val: str) -> str:
        return re.sub(r"(-?\d+(?:\.\d+)?)px",
                      lambda m: f"{round(float(m.group(1)) * scale * 2) / 2:g}rpx", val)

    lines = ["// Generated by token_emit.py — do not edit by hand.",
             f"// rpx conversion: 750rpx = {design_width}px design width (×{scale:g}).",
             "page {"]
    for k in sorted(flat):
        var = f"--{_kebab(k.replace('.', '-'))}"
        note = descs.get(k) if descs else None
        lines.append(f"  {var}: {to_rpx(str(flat[k]))};" + (f"  /* {note} */" if note else ""))
    lines.append("}")
    return "\n".join(lines)


DEMO = {
    "color": {
        "accent": {"500": {"$value": "oklch(0.63 0.17 261.7)"}},
        "bg": {"$value": "oklch(0.16 0.02 260)"},
        "text": {"$value": "oklch(0.93 0.01 260)"},
    },
    # shadcn-bridge naming (platforms/shadcn-tailwind.md §1): semantic pairs
    # pass through the emitter unchanged — deliverable form for components.json projects
    "semantic": {
        "primary": {"$value": "{color.accent.500}",
                    "$description": "measured 6.18:1 AA on --background | Lc 62 (APCA, informational)"},
        "primary-foreground": {"$value": "oklch(0.985 0 0)"},
        "muted-foreground": {"$value": "oklch(0.556 0 0)",
                             "$description": "shadcn bridge: text-muted-foreground"},
    },
    "radius": {"md": {"$value": "12px"}},
    "space": {"unit": {"$value": "4px"}},
    "duration": {"base": {"$value": "200ms"}},
    "ease": {"spring": {"$value": "linear(0, 0.065, 1)"}},
    "accentRef": {"$value": "{color.accent.500}"},  # alias resolution demo
}

def build_flat(doc: dict, descs: dict | None = None) -> dict:
    flat = {}
    for key, val in doc.items():
        if isinstance(val, dict) and ("$value" in val or "value" in val):
            flat[key] = val.get("$value", val.get("value"))
        elif isinstance(val, dict):
            flat.update(_flatten(val, key, descs))
        else:
            flat[key] = val
    return resolve_aliases(flat)

def selftest() -> int:
    fails = []
    def check(name, ok, detail=""):
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f": {detail}" if detail else ""))
        if not ok: fails.append(name)

    flat = build_flat(DEMO)
    descs = {}
    build_flat(DEMO, descs)
    print("selftest: flattening & aliases")
    check("$value extracted", flat.get("color.accent.500") == "oklch(0.63 0.17 261.7)")
    check("alias resolved", flat.get("accentRef") == "oklch(0.63 0.17 261.7)", str(flat.get("accentRef")))

    css = emit_css(flat, descs)
    sw = emit_swift(flat)
    kt = emit_kotlin(flat)
    print("selftest: emitters")
    check("css var line", "--color-accent-500: oklch(0.63 0.17 261.7);" in css)
    check("css alias var", "--accent-ref: oklch(0.63 0.17 261.7);" in css)
    check("swift constant", 'static let colorAccent500: String = "oklch(0.63 0.17 261.7)"' in sw)
    check("kotlin constant", 'val colorAccent500: String = "oklch(0.63 0.17 261.7)"' in kt)
    check("kebab conversion", "--ease-spring:" in css and "radius-md" in css)

    print("selftest: shadcn-bridge & description provenance (2026-10-18)")
    check("shadcn semantic pair passes through", "--semantic-primary-foreground: oklch(0.985 0 0);" in css)
    check("$description -> css comment (measured + Lc)", "/* measured 6.18:1 AA on --background | Lc 62 (APCA, informational) */" in css)

    print("selftest: wxss/rpx target")
    wx = emit_wxss(flat, descs)
    check("wxss page selector", wx.startswith("// Generated by token_emit.py") and "page {" in wx)
    check("px doubled to rpx (4px→8rpx, 12px→24rpx)",
          "--radius-md: 24rpx;" in wx and "--space-unit: 8rpx;" in wx)
    check("non-px values untouched (ms/oklch)",
          "--duration-base: 200ms;" in wx and "--color-accent-500: oklch(0.63 0.17 261.7);" in wx)
    check("description comment survives into wxss", "/* measured 6.18:1 AA" in wx)

    if fails:
        print(f"SELFTEST FAILED: {fails}"); return 1
    print("SELFTEST PASSED (all anchors green)"); return 0

def main() -> int:
    ap = argparse.ArgumentParser(description="DTCG tokens -> CSS/Swift/Kotlin")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("input", nargs="?", help="tokens JSON file")
    ap.add_argument("--demo", action="store_true", help="use the built-in demo token set")
    ap.add_argument("--wxss", action="store_true", help="also emit tokens.wxss (WeChat: page selector, px→rpx at 375 design width) — keeps miniprogram tokens generated, not hand-synced")
    ap.add_argument("--out-dir", default="tokens-out")
    a = ap.parse_args()

    if a.selftest: return selftest()
    if a.demo:
        doc = DEMO
    elif a.input:
        with open(a.input, encoding="utf-8") as f: doc = json.load(f)
    else:
        ap.error("give a tokens JSON file, --demo, or --selftest")

    import os
    os.makedirs(a.out_dir, exist_ok=True)
    descs = {}
    flat = build_flat(doc, descs)
    outputs = {"tokens.css": emit_css(flat, descs), "tokens.swift": emit_swift(flat), "tokens.kt": emit_kotlin(flat)}
    if a.wxss:
        outputs["tokens.wxss"] = emit_wxss(flat, descs)
    for name, content in outputs.items():
        path = os.path.join(a.out_dir, name)
        with open(path, "w", encoding="utf-8") as f: f.write(content + "\n")
        print(f"wrote {path} ({len(content)} chars, {len(flat)} tokens)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
